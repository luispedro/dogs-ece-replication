"""Candidate-origin features in noncoding DNA around replication genes.

Three simple, auditable statistics are computed for each region and compared
with composition-matched backgrounds generated by a first-order Markov chain:

* ``dr_copies`` - copies of the most frequent k-mer (direct repeats / iterons).
* ``ir_stem`` - longest perfect inverted-repeat stem with a short loop
  (potential stem-loop / hairpin, e.g. a dso nick-site hairpin).
* ``at_max`` - maximum AT fraction in a sliding window (AT-rich DNA unwinding element).

For DR and IR the Markov chain is trained on the region itself, so only the
excess of repeat structure over what local composition predicts is tested.
For AT richness the chain is trained on the whole element, so the test asks
whether the region is more AT-rich than the element's background.
These are supporting evidence only and never classify a mechanism alone.
"""
import numpy as np

ENC = {"A": 0, "C": 1, "G": 2, "T": 3}


def encode(seq):
    return np.array([ENC.get(c, -1) for c in seq.upper()], dtype=np.int8)


def markov_model(codes):
    codes = codes[codes >= 0]
    trans = np.ones((4, 4))  # Laplace pseudocounts
    if len(codes) > 1:
        np.add.at(trans, (codes[:-1], codes[1:]), 1)
    trans /= trans.sum(axis=1, keepdims=True)
    init = np.bincount(codes, minlength=4) + 1.0
    return init / init.sum(), trans


def markov_sample(model, n, rng, count):
    init, trans = model
    cum = np.cumsum(trans, axis=1)
    out = np.empty((count, n), dtype=np.int8)
    out[:, 0] = rng.choice(4, size=count, p=init)
    u = rng.random((count, n))
    for i in range(1, n):
        prev = out[:, i - 1]
        out[:, i] = (u[:, i][:, None] > cum[prev]).sum(axis=1)
    return np.minimum(out, 3)


def dr_copies(codes, k):
    """Maximum number of non-overlapping occurrences of any k-mer (same strand)."""
    n = len(codes)
    if n < k:
        return 0
    valid = codes >= 0
    vals = np.zeros(n - k + 1, dtype=np.int64)
    ok = np.ones(n - k + 1, dtype=bool)
    for j in range(k):
        vals = vals * 4 + np.where(valid[j:n - k + 1 + j], codes[j:n - k + 1 + j], 0)
        ok &= valid[j:n - k + 1 + j]
    vals = vals[ok]
    pos = np.nonzero(ok)[0]
    if len(vals) == 0:
        return 0
    order = np.lexsort((pos, vals))
    vals, pos = vals[order], pos[order]
    best, i = 1, 0
    while i < len(vals):
        j = i
        cnt, last = 1, pos[i]
        while j + 1 < len(vals) and vals[j + 1] == vals[i]:
            j += 1
            if pos[j] - last >= k:
                cnt += 1
                last = pos[j]
        best = max(best, cnt)
        i = j + 1
    return int(best)


def ir_stem(codes, loop_min, loop_max, max_stem):
    """Longest perfect inverted-repeat stem with loop length in [loop_min, loop_max]."""
    n = len(codes)
    comp = np.where(codes >= 0, 3 - codes, -2)
    best = 0
    for loop in range(loop_min, loop_max + 1):
        # inner pair: left base at i, right base at i + loop + 1
        m = n - loop - 1
        if m <= 0:
            continue
        run = np.zeros(m, dtype=np.int32)
        alive = np.ones(m, dtype=bool)
        for k in range(max_stem):
            # pairs (i - k, i + loop + 1 + k) exist for k <= i < m - k
            width = m - 2 * k
            if width <= 0:
                break
            match = np.zeros(m, dtype=bool)
            match[k:m - k] = codes[0:width] == comp[loop + 1 + 2 * k:loop + 1 + 2 * k + width]
            alive &= match
            if not alive.any():
                break
            run += alive
        best = max(best, int(run.max()))
    return best


def at_max(codes, window):
    if len(codes) < window:
        window = max(1, len(codes))
    at = ((codes == 0) | (codes == 3)).astype(float)
    return float(np.convolve(at, np.ones(window), "valid").max() / window)


def region_stats(codes, cfg):
    return {
        "dr_copies": dr_copies(codes, cfg["dr_kmer"]),
        "ir_stem": ir_stem(codes, cfg["ir_loop_min"], cfg["ir_loop_max"], cfg["ir_max_stem"]),
        "at_max": at_max(codes, cfg["at_window"]),
    }


def test_region(seq, element_seq, cfg, seed):
    """Observed statistics plus empirical upper-tail P-values against Markov backgrounds."""
    codes = encode(seq)
    obs = region_stats(codes, cfg)
    rng = np.random.default_rng(seed)
    nb = cfg["n_background"]
    local = markov_sample(markov_model(codes), len(codes), rng, nb)
    glob = markov_sample(markov_model(encode(element_seq)), len(codes), rng, nb)
    dr_bg = np.array([dr_copies(s, cfg["dr_kmer"]) for s in local])
    ir_bg = np.array([ir_stem(s, cfg["ir_loop_min"], cfg["ir_loop_max"], cfg["ir_max_stem"]) for s in local])
    at_bg = np.array([at_max(s, cfg["at_window"]) for s in glob])
    p = lambda bg, o: float((1 + (bg >= o).sum()) / (len(bg) + 1))
    return {
        **obs,
        "dr_p": p(dr_bg, obs["dr_copies"]),
        "ir_p": p(ir_bg, obs["ir_stem"]),
        "at_p": p(at_bg, obs["at_max"]),
        "dr_bg_median": float(np.median(dr_bg)),
        "ir_bg_median": float(np.median(ir_bg)),
        "at_bg_median": float(np.median(at_bg)),
    }


def circular_slice(seq, start, end):
    """1-based inclusive slice of a circular sequence; end < start wraps."""
    if end >= start:
        return seq[start - 1:end]
    return seq[start - 1:] + seq[:end]


def flanking_regions(gene, intergenic, L, flank):
    """Intergenic regions immediately upstream and downstream of a gene (strand-aware).

    Returns a list of (side, start, end) with each region trimmed to ``flank``
    nt closest to the gene.
    """
    gs, ge, strand = gene["start"], gene["end"], gene["strand"]
    left = right = None
    for s, e in intergenic:
        if e % L + 1 == gs:
            left = (s, e)
        if ge % L + 1 == s:
            right = (s, e)
    out = []

    def length(s, e):
        return e - s + 1 if e >= s else L - s + 1 + e

    for side_lr, reg in (("left", left), ("right", right)):
        if reg is None:
            continue
        s, e = reg
        if length(s, e) > flank:
            if side_lr == "left":
                s = (e - flank) % L + 1
            else:
                e = (s + flank - 2) % L + 1
        side = {("left", "+"): "upstream", ("right", "+"): "downstream",
                ("left", "-"): "downstream", ("right", "-"): "upstream"}[(side_lr, strand)]
        out.append((side, s, e))
    return out


def motif_hits(seq, motif, max_mismatches):
    """Positions (1-based, circular) where `motif` or its reverse complement matches with <= max mismatches."""
    s = encode(seq)
    m = len(motif)
    s = np.concatenate([s, s[:m - 1]])
    n = len(seq)
    out = []
    rc = motif[::-1].translate(str.maketrans("ACGT", "TGCA"))
    for strand, q in (("+", motif), ("-", rc)):
        qc = encode(q)
        mism = np.zeros(n, dtype=np.int32)
        for i in range(m):
            mism += s[i:i + n] != qc[i]
        for p in np.nonzero(mism <= max_mismatches)[0]:
            out.append((int(p) + 1, strand, int(mism[p])))
    return out
